#pragma once
#include <d3d11.h>
#include <DirectXMath.h>

using namespace DirectX;

//-----------------------------------------------------------
// シャドウマップ（影の計算）を管理する
//
// 仕組みの概要：
//   1. 光源の視点からシーンを描画し、「深度バッファ」に保存
//      （どこが光の当たる場所か記録する）
//   2. 通常のカメラ視点で描画するとき、
//      その深度バッファを参照して「光が届かない場所 = 影」と判定する
//
// 使い方（Main.cpp）：
//   ShadowMap::Initialize()     → 起動時に1回
//   ShadowMap::BeginShadowPass() → 影描画パス開始
//   Model::DrawShadowAll()       → 影を落とすモデルを描画
//   ShadowMap::EndShadowPass()   → 影描画パス終了
//   ShadowMap::BindToShader()    → 通常描画パスでシャドウマップをシェーダーに渡す
//   （通常描画）
//   ShadowMap::UnbindFromShader() → シャドウマップの割り当て解除
//   ShadowMap::Release()         → 終了時に1回
//-----------------------------------------------------------
namespace ShadowMap
{
	// シャドウマップのサイズ（大きいほど影が細かくなるが重くなる）
	const int SHADOW_MAP_SIZE = 2048;

	//-----------------------------------------------------------
	// シャドウパス用のコンスタントバッファ
	// 光源の視点でシーンを描画するときに使う
	//-----------------------------------------------------------
	struct SHADOW_CB
	{
		XMMATRIX matWVP;	// 光源から見た ワールド×ビュー×プロジェクション行列
	};

	//-----------------------------------------------------------
	// 初期化
	// シャドウマップに必要なテクスチャ・バッファを作成する
	//-----------------------------------------------------------
	void Initialize();

	//-----------------------------------------------------------
	// 後片付け（プログラム終了時に呼ぶ）
	//-----------------------------------------------------------
	void Release();

	//-----------------------------------------------------------
	// 光源の方向をセット
	// 引数：lightDir　光の向いている方向（例：{-1, -1, 1}）
	//-----------------------------------------------------------
	void SetLightDir(XMFLOAT3 lightDir);

	//-----------------------------------------------------------
	// シャドウ（影）のON / OFF
	// 引数：enable   true=影あり / false=影なし
	//-----------------------------------------------------------
	void SetEnable(bool enable);

	//-----------------------------------------------------------
	// 今シャドウが有効か調べる
	// 戻値：true=有効
	//-----------------------------------------------------------
	bool IsEnabled();

	//-----------------------------------------------------------
	// 光源のビュー×プロジェクション行列を取得する
	// FbxParts の Draw から使う（コンスタントバッファに渡すため）
	//-----------------------------------------------------------
	XMMATRIX GetLightViewProjection();

	//-----------------------------------------------------------
	// 影描画パス開始
	// 光源の視点でシーンを描画する準備をする
	//-----------------------------------------------------------
	void BeginShadowPass();

	//-----------------------------------------------------------
	// 影描画パス終了
	// 通常の描画に戻す
	//-----------------------------------------------------------
	void EndShadowPass();

	//-----------------------------------------------------------
	// シャドウマップをシェーダーに渡す（t1スロット）
	// 通常描画パスの BeginDraw の後に呼ぶ
	//-----------------------------------------------------------
	void BindToShader();

	//-----------------------------------------------------------
	// シャドウマップのシェーダーへの割り当てを解除する
	// 通常描画パスの EndDraw の後に呼ぶ
	//-----------------------------------------------------------
	void UnbindFromShader();

	//-----------------------------------------------------------
	// シャドウパスで1モデルのコンスタントバッファを更新してシェーダーに送る
	// 引数：worldMatrix　そのモデルのワールド行列
	//-----------------------------------------------------------
	void UpdateAndBindConstantBuffer(XMMATRIX worldMatrix);
};
